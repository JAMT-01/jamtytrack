import fs from 'node:fs';
import assert from 'node:assert/strict';
import {Script} from 'node:vm';
import {rewardCelebration} from '../worker/habit-rewards.js';
const root=new URL('../',import.meta.url);
const clientPath=new URL('worker/habits-client.js',root);
let client=fs.readFileSync(clientPath,'utf8').replaceAll('\r\n','\n');
client=client.replace(/\/\/ REWARD CELEBRATION START[\s\S]*?\/\/ REWARD CELEBRATION END/,
  '// REWARD CELEBRATION START\n'+rewardCelebration.toString()+'\n  // REWARD CELEBRATION END');
new Script(client);
fs.writeFileSync(clientPath,client);
const sourcePath=new URL('worker/habits-assets.ts',root);
let source=fs.readFileSync(sourcePath,'utf8');
source=source.replace(/\/\/ Generated from worker\/habits-client\.js by tools\/sync-habits-ui\.mjs\.\r?\n/g,'');
const start=source.indexOf('export const HABITS_CLIENT_SOURCE');
const end=source.indexOf('export function habitsClientResponse');
assert(start>=0&&end>start);
source=source.slice(0,start)+'// Generated from worker/habits-client.js by tools/sync-habits-ui.mjs.\nexport const HABITS_CLIENT_SOURCE = '+JSON.stringify(client)+';\n\n'+source.slice(end);
source=source.replace(/(\/habits-client\.js\?v=)[^"\s]+/g,'$120260914-near-goal');
fs.writeFileSync(sourcePath,source);
const bundlePath=new URL('dist/worker.js',root);
let bundle=fs.readFileSync(bundlePath,'utf8');
const from=bundle.indexOf('const HABITS_CLIENT_SOURCE =');
const to=bundle.indexOf('function habitsClientResponse()',from);
assert(from>=0&&to>from);
bundle=bundle.slice(0,from)+'const HABITS_CLIENT_SOURCE = '+JSON.stringify(client)+';\n'+bundle.slice(to);
bundle=bundle.replace(/(\/habits-client\.js\?v=)[^"\s]+/g,'$120260914-near-goal');
fs.writeFileSync(bundlePath,bundle);
console.log('Updated the Habits client in its source wrapper and the existing production bundle.');
